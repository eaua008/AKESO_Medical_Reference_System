"""Body part descriptions for the Body System Explorer (migration 052).

One BodyPartInfo describes a concept (a part name with left/right removed,
"femur") or a group ("group:quadriceps"), on both sides. It is public
reference data, written from public-domain sources and reviewed by the
owner (database/body_parts_review), synced and cached offline like the
encyclopedia. Nothing in it is generated by the app.
"""

import json
import re
from dataclasses import asdict, dataclass, field

# Layer -> the "For students" details shown for it, in order (see BRIEF.md).
DETAIL_FIELDS = {
    "bone": (("type", "Type"), ("joints", "Joints"), ("landmarks", "Landmarks")),
    "muscle": (("origin", "Origin"), ("insertion", "Insertion"), ("action", "Action"),
               ("nerve_supply", "Nerve supply"), ("blood_supply", "Blood supply")),
    "organ": (("functions", "Main functions"), ("blood_supply", "Blood supply"),
              ("nerve_supply", "Nerve supply"), ("lymph_drainage", "Lymph drainage")),
    "vessel": (("origin", "Origin"), ("territory", "Supplies / drains"),
               ("branches", "Main branches")),
    "nerve": (("origin", "Origin"), ("type", "Type"), ("supplies", "Supplies")),
}


def concept_key(name: str) -> str:
    """'long head of left biceps brachii' -> 'long head of biceps brachii'."""
    return re.sub(r"\s+", " ", re.sub(r"\b(left|right)\b", " ", (name or "").lower())).strip()


@dataclass
class ClinicalNote:
    text: str
    disease_id: str = ""


@dataclass
class PartSource:
    title: str
    url: str
    licence: str = ""


@dataclass
class BodyPartInfo:
    key: str
    display_name: str
    kind: str = "part"                       # part | group
    fma_ids: list[str] = field(default_factory=list)
    layer: str = ""
    system: str = ""
    aliases: list[str] = field(default_factory=list)
    summary_plain: str = ""
    function_plain: str = ""
    description: str = ""
    location: str = ""
    details: dict = field(default_factory=dict)
    clinical: list[ClinicalNote] = field(default_factory=list)
    exam_tip: str = ""
    sources: list[PartSource] = field(default_factory=list)
    status: str = "published"

    @property
    def is_draft(self) -> bool:
        return self.status != "published"

    def detail_rows(self) -> list[tuple[str, str]]:
        """(title, text) for the layer's filled details, in their usual order."""
        return [(title, str(self.details.get(k, "")).strip())
                for k, title in DETAIL_FIELDS.get(self.layer, ())
                if str(self.details.get(k, "")).strip()]

    def has_student_text(self) -> bool:
        return bool(self.description or self.location or self.detail_rows())

    @classmethod
    def from_row(cls, row: dict) -> "BodyPartInfo":
        """A body_part_info row (PostgREST or the admin preview) or a cached dict."""
        def text(k: str) -> str:
            return str(row.get(k) or "").strip()
        return cls(
            key=text("key"), display_name=text("display_name") or text("key"),
            kind=text("kind") or "part", fma_ids=[str(x) for x in row.get("fma_ids") or []],
            layer=text("layer"), system=text("system"),
            aliases=[str(a) for a in row.get("aliases") or [] if str(a).strip()],
            summary_plain=text("summary_plain"), function_plain=text("function_plain"),
            description=text("description"), location=text("location"),
            details=row.get("details") if isinstance(row.get("details"), dict) else {},
            clinical=[ClinicalNote(str(c.get("text") or "").strip(), str(c.get("disease_id") or ""))
                      for c in row.get("clinical") or [] if isinstance(c, dict) and c.get("text")],
            exam_tip=text("exam_tip"),
            sources=[PartSource(str(s.get("title") or ""), str(s.get("url") or ""),
                                str(s.get("licence") or ""))
                     for s in row.get("sources") or [] if isinstance(s, dict) and s.get("url")],
            status=text("status") or "published",
        )


def parts_to_json(parts: list[BodyPartInfo]) -> str:
    return json.dumps([asdict(p) for p in parts], ensure_ascii=False)


def parts_from_json(text: str) -> list[BodyPartInfo]:
    try:
        return [BodyPartInfo.from_row(row) for row in json.loads(text or "[]")]
    except (ValueError, TypeError, AttributeError):
        return []                         # a damaged copy: the next sync replaces it
